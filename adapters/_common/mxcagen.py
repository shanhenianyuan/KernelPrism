def load_payload():
    """读 stdin JSON payload（_call_hook 契约：{...payload, run_id}）。"""
    raw = sys.stdin.read() if not sys.stdin.isatty() else '{}'
    try:
        return json.loads(raw) or {}
    except json.JSONDecodeError:
        return {}


def emit(result):
    """stdout 尾行 JSON（_call_hook 契约：splitlines()[-1] 被 json.loads）。"""
    print(json.dumps(result, ensure_ascii=False))
    sys.stdout.flush()


def my_platform(payload) -> str:
    """从 payload 推断平台：vendor_id 明确指定；否则按工具链存在性探测，再缺省 lingspeed。"""
    vid = ''
    for key in ('vendor_id', 'vendor', 'platform'):
        v = payload.get(key)
        if isinstance(v, str) and v in PLATFORMS:
            vid = v
            break
    if vid:
        return vid
    for pid in PLATFORMS:
        tc = locate_toolchain(pid)
        if tc['found']:
            return pid
    return 'lingspeed'


def build_or_fail(payload, mode):
    """compile/verify/perf 共用失败路径：工具链缺失时返回 (False, result_dict)。"""
    pf_name = my_platform(payload)
    pf = platform(pf_name)
    tc = locate_toolchain(pf_name)
    if not tc['found']:
        return False, {
            'build_ok': False, 'exit_code': 1,
            'detail': '%s compiler not found (%s toolchain missing; candidates: %s)'
                      % (pf['x_lang'] + '-cc', pf['runtime_lib'],
                         ', '.join([x for x in pf['home_candidates']])),
            'platform': pf_name,
        }
    return True, tc


