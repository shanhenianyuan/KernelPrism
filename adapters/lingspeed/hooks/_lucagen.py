# ---------------------------------------------------------------------------
# 工具链定位
# ---------------------------------------------------------------------------
def locate_toolchain():
    """返回 dict {lscc, lucca_home, device_ok, found}；lscc 不存在返回 found=False。"""
    lscc = None
    lucca_home = None
    for cand in LUCA_HOME_CANDIDATES:
        if not cand:
            continue
        c = os.path.join(cand, LSCC_REL)
        if os.path.isfile(c) and os.access(c, os.X_OK):
            lscc = c
            lucca_home = cand
            break
    device_ok = os.path.exists(DEV_NODE)
    return {
        'lscc': lscc,
        'lucca_home': lucca_home,
        'device_ok': device_ok,
        'found': lscc is not None,
    }


def toolchain_summary(tc):
    return {
        'compiler': 'lscc',
        'version': LUCA_VERSION,
        'path': tc.get('lscc') or 'not-found',
        'device': DEV_NODE + (' (present)' if tc.get('device_ok') else ' (missing)'),
        'luca_home': tc.get('lucca_home'),
    }


# ---------------------------------------------------------------------------
# LUCA C++ 源生成
# ---------------------------------------------------------------------------
def _resolve_block(kernel_source):
    """从 kernel_source[source_tree][mechanism] 提取 BLK。无则默认 256。"""
    blk = 256
    try:
        st = kernel_source.get('source_tree') or {}
        mech = st.get('mechanism') or {}
        # mechanism 可能是 dict 或描述串；兼容 dict 字段与字符串内 'blk=n'
        if isinstance(mech, dict):
            for k in ('blk', 'block', 'block_size', 'threads'):
                v = mech.get(k)
                if isinstance(v, int) and 32 <= v <= 1024:
                    blk = v
                    break
        elif isinstance(mech, str):
            m = re.search(r'blk[=:](\d+)', mech)
            if m:
                blk = int(m.group(1))
    except Exception:
        pass
    return max(32, min(1024, blk))


def _resolve_n(case_or_shape, default_n):
    """从 case dict（{'shape': [...]}）或裸 shape list 解析元素总数。"""
    if isinstance(case_or_shape, dict):
        shape = case_or_shape.get('shape') or []
    elif isinstance(case_or_shape, (list, tuple)):
        shape = list(case_or_shape)
    else:
        shape = []
    n = 1
    for s in shape:
        n *= int(s)
    return max(1, n) if shape else default_n


def gen_add_cpp(kernel_source, case, mode='compile', n=None):
    """生成单档 LUCA C++ 源文本。

    kernel_source : _s2 产物（source_tree={kind:'template', mechanism:...}，语言 reference）
    case          : {'id','shape','dtype'} 或裸 shape
    mode          : compile|verify|perf（本模板同一骨架，均含 RESULT 输出；
                    compile 模式仅用于冒烟编译+运行自检）
    n             : 元素总数；缺省从 case shape 求积
    """
    n = n or _resolve_n(case, default_n=8192)
    blk = _resolve_block(kernel_source)
    grid = (n + blk - 1) // blk
    # 计时规模自适应：小 n 加大迭代次数，大 n 减少（控制运行时长在 timeout 内）
    if n <= 1024:
        warm, segs, seg_iters = 200, 6, 200
    elif n <= 65536:
        warm, segs, seg_iters = 60, 6, 60
    elif n <= 1048576:
        warm, segs, seg_iters = 20, 5, 20
    else:
        warm, segs, seg_iters = 5, 4, 5

    src = _ADD_TEMPLATE
    repl = {
        _T['OP_ID']: str((kernel_source or {}).get('op_id') or 'add'),
        _T['MODE']: mode,
        _T['N_ELEMS']: str(n),
        _T['BLK']: str(blk),
        _T['GRID']: str(grid),
        _T['WARM']: str(warm),
        _T['SEGS']: str(segs),
        _T['SEG_ITERS']: str(seg_iters),
        _T['KERNEL']: '',
    }
    for k, v in repl.items():
        src = src.replace(k, v)
    return src


# ---------------------------------------------------------------------------
# 编译 / 运行 / 解析
# ---------------------------------------------------------------------------
def lscc_compile(lscc, src_text, out_bin, log_path=None, timeout=300):
    """lscc -x luca 编译单档 C++。返回 (exit_code, log_text)。"""
    tmp_src = out_bin + '.luca.cpp'
    with open(tmp_src, 'w', encoding='utf-8') as f:
        f.write(src_text)
    cmd = [lscc, '-x', 'luca', tmp_src, '-o', out_bin]
    try:
        r = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout)
        log = r.stdout + r.stderr
    except subprocess.TimeoutExpired as e:
        log = ('lscc timeout after %ds' % timeout) + (e.stdout or b'').decode('utf-8', 'replace')
        r = None
    if log_path:
        with open(log_path, 'w', encoding='utf-8') as f:
            f.write(log)
    return (r.returncode if r is not None else -1), log


def run_binary(bin_path, timeout=300):
    """运行编译产物，捕获 stdout/stderr。返回 (exit_code, stdout, stderr)。"""
    try:
        r = subprocess.run([bin_path], capture_output=True, text=True, timeout=timeout)
        return r.returncode, r.stdout, r.stderr
    except subprocess.TimeoutExpired:
        return -1, '', 'binary timeout after %ds' % timeout
    except FileNotFoundError:
        return -2, '', 'binary not found: %s' % bin_path


RESULT_RE = re.compile(
    r'RESULT\s+per_iter_ms=([\d.eE+-]+)\s+std_ms=([\d.eE+-]+)\s+rounds=(\d+)\s+'
    r'max_abs_err=([\d.eE+-]+)\s+max_rel_err=([\d.eE+-]+)\s+bad=(\d+)')


def parse_output(stdout):
    """解析程序 stdout：RESULT 行 + @DONE@ 协议。返回 dict（字段可能缺失）。"""
    out = {'done': False, 'per_iter_ms': None, 'std_ms': None,
           'rounds': None, 'max_abs_err': None, 'max_rel_err': None, 'bad': None}
    if '@DONE@' in stdout:
        out['done'] = True
    m = RESULT_RE.search(stdout)
    if m:
        out['per_iter_ms'] = float(m.group(1))
        out['std_ms'] = float(m.group(2))
        out['rounds'] = int(m.group(3))
        out['max_abs_err'] = float(m.group(4))
        out['max_rel_err'] = float(m.group(5))
        out['bad'] = int(m.group(6))
    return out


# ---------------------------------------------------------------------------
# hook 公共外壳
# ---------------------------------------------------------------------------
def load_payload():
    """读 stdin JSON payload（_call_hook 契约：{...payload, run_id}）。"""
    raw = sys.stdin.read() if not sys.stdin.isatty() else '{}'
    try:
        return json.loads(raw) or {}
    except json.JSONDecodeError:
        return {}


def emit(result):
    """stdout 尾行 JSON（_call_hook 契约：splitlines()[-1] 被 json.loads）。"""
    print(json.dumps(result, ensure_ascii=False))
    sys.stdout.flush()


def build_or_fail(payload, mode):
    """三 hook 共用失败路径：工具链缺失/编译失败/运行失败时返回 (ok, result_dict)。
    成功时返回 (True, result_dict) 由调用方补齐字段。"""
    tc = locate_toolchain()
    if not tc['found']:
        return False, {
            'build_ok': False, 'exit_code': 1,
            'detail': 'lscc not found (LUCA toolchain missing; candidates: %s)'
                      % ', '.join([x for x in LUCA_HOME_CANDIDATES if x]),
        }
    return True, tc


# ---------------------------------------------------------------------------
# 自检入口（--toolchain / -t）
# ---------------------------------------------------------------------------
if __name__ == '__main__':
    if '-t' in sys.argv or '--toolchain' in sys.argv:
        t = locate_toolchain()
        print(json.dumps(toolchain_summary(t), ensure_ascii=False, indent=2))
        sys.exit(0 if t['found'] else 1)
    print('_lucagen.py — shared tooling for lingspeed hooks (import me)')
